const assert=require('node:assert/strict');
const Z=require('../zone1.js');
assert.deepEqual(Z.groupQuotas(100),{1:30,2:25,3:25,4:20});
assert.deepEqual(Z.groupQuotas(1),{1:1,2:0,3:0,4:0});
let c=Z.calculate([{id:'a',name:'A',raw:30,bonus:20,knocks:1,group:1}],{speed:2,lossPerKnock:10,inputMode:'raw'});
assert.ok(Math.abs(c.total-30*1.2*.9571*.9)<1e-10);
c=Z.calculate([{id:'a',name:'A',raw:30,bonus:20,knocks:1,group:1}],{speed:2,lossPerKnock:10,inputMode:'final'});
assert.equal(c.total,30);
assert.equal(c.overCap,false);
assert.equal(Z.calculate([{id:'a',name:'A',raw:60},{id:'b',name:'B',raw:50}],{inputMode:'final'}).overCap,true);
const members=[1,2,3,4].map(g=>({id:`m${g}`,name:`G${g}`,group:g,effective:12}));
let seed=9271;const rng=()=>{seed=(seed*1664525+1013904223)>>>0;return seed/4294967296;};
const r=Z.draw({members,items:[{id:'g',name:'보석',quantity:30,value:100},{id:'s',name:'골드',quantity:70,value:10}]},rng);
assert.equal(r.rewards.length,100);
assert.equal(r.held.length,0);
assert.equal(r.rewards.reduce((s,x)=>s+x.value,0),3700);
assert.deepEqual(Object.fromEntries([1,2,3,4].map(g=>[g,r.groupStats[g].assigned])),{1:30,2:25,3:25,4:20});
const empty=Z.draw({members:[members[0]],items:[{name:'소모품',quantity:20,value:1}]},rng);
assert.equal(empty.held.length,14);
assert.equal(empty.rewards.length,6);
